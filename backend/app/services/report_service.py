def _utc(dt: datetime | None) -> str | None:
    """Format a datetime as UTC. Naive values are UTC already (that is how they are stored)."""
    if dt is None:
        return None
    if dt.tzinfo is not None:
        dt = dt.astimezone(timezone.utc)
    return dt.strftime('%Y-%m-%d %H:%M:%S')


def _utc_from_iso(value) -> str | None:
    try:
        return _utc(datetime.fromisoformat(str(value)))
    except (TypeError, ValueError):
        return str(value) if value else None


def _load_json(text, expected):
    try:
        value = json.loads(text) if text else None
    except (TypeError, ValueError):
        value = None
    return value if isinstance(value, expected) else expected()


def _format_bytes(size: int) -> str:
    if size < 1024:
        return f'{size} B'
    if size < 1024 * 1024:
        return f'{size / 1024:.1f} KB'
    return f'{size / 1024 / 1024:.2f} MB'


def _stored_evidence_path(evidence: Evidence | None) -> str | None:
    """Absolute path of the stored evidence file, if it is on disk."""
    if not evidence or not evidence.file_path:
        return None
    path = os.path.join(current_app.config.get('UPLOAD_FOLDER', ''), os.path.basename(evidence.file_path))
    return path if os.path.isfile(path) else None


def check_evidence_integrity(evidence: Evidence | None) -> dict:
    """
    Re-hash the stored evidence file and compare it with the SHA-256 recorded at
    upload. Read-only: the evidence record is not modified.

    'state' is one of: match, mismatch, unavailable, no_hash, no_evidence.
    """
    if evidence is None:
        return {'state': 'no_evidence',
                'state_label': 'NO EVIDENCE FILE — no evidence record exists for this detection, '
                               'so there is no file hash to verify.'}

    result = {
        'sha256': evidence.sha256_hash or None,
        'md5': evidence.md5_hash or None,
        'recorded_at': _utc(evidence.created_at),
    }
    if not evidence.sha256_hash:
        return {**result, 'state': 'no_hash',
                'state_label': 'NOT VERIFIED — no SHA-256 hash was recorded for this evidence.'}

    path = _stored_evidence_path(evidence)
    if not path:
        return {**result, 'state': 'unavailable',
                'state_label': 'NOT VERIFIED — the stored evidence file is not available, so the recorded '
                               'hash could not be re-checked.'}

    try:
        actual = calculate_sha256(path)
    except Exception:
        return {**result, 'state': 'unavailable',
                'state_label': 'NOT VERIFIED — the stored evidence file could not be read.'}

    checked_at = _utc(datetime.now(timezone.utc))
    if actual.lower() == evidence.sha256_hash.lower():
        return {**result, 'state': 'match', 'checked_at': checked_at,
                'state_label': f'MATCH — the stored evidence file was re-hashed on {checked_at} UTC and its '
                               'SHA-256 equals the recorded value.'}
    return {**result, 'state': 'mismatch', 'checked_at': checked_at, 'actual_sha256': actual,
            'state_label': f'MISMATCH — the stored evidence file was re-hashed on {checked_at} UTC and its '
                           'SHA-256 differs from the recorded value. The stored file has been changed or '
                           'replaced since the hash was recorded.'}


def _file_info(detection: Detection, evidence: Evidence | None, meta: dict) -> dict:
    """File facts for the report, re-measured from the stored evidence file when it exists."""
    stored_path = _stored_evidence_path(evidence)
    info = {
        'name': detection.file_name,
        'media_type': {'image': 'Image', 'video': 'Video', 'url': 'URL'}.get(detection.file_type, detection.file_type),
        'uploaded_at': _utc(detection.created_at),
    }

    if detection.file_type == 'url':
        info['name'] = None
        info['source_url'] = detection.source_url or detection.file_name
        info['detected_format'] = info['mime'] = 'Not applicable (no file was retrieved)'
        return info

    if stored_path:
        identity = extract_basic_metadata(stored_path, detection.file_name, meta.get('clientMimeType'))
        info['source_note'] = (
            'File size, detected format and MIME type were measured by FAKENIX from the stored file bytes for '
            'this report. The file name and its extension are as supplied by the uploader.'
        )
    else:
        # Only trust recorded format fields that came from byte-level detection.
        identity = meta if 'detectedFormat' in meta else {
            'fileExtension': os.path.splitext(detection.file_name or '')[1].lower() or None,
            'detectedFormat': meta.get('format') if detection.file_type == 'image' else None,
        }
        info['source_note'] = (
            'The stored file was not available when this report was generated; values are as recorded at upload '
            'and could not be re-measured.'
        )

    size_bytes = identity.get('fileSizeBytes')
    if size_bytes is not None:
        info['size_bytes'] = size_bytes
        info['size_display'] = _format_bytes(size_bytes)
    elif re.search(r'\d\s*(B|KB|MB|GB)$', detection.file_size or ''):
        info['size_display'] = detection.file_size

    info['extension'] = identity.get('fileExtension')
    info['detected_format'] = identity.get('detectedFormat')
    info['mime'] = identity.get('mimeType') if identity.get('detectedFormat') else None
    info['inconsistencies'] = list(identity.get('inconsistencies') or [])

    width, height = meta.get('width'), meta.get('height')
    if width and height:
        info['dimensions'] = f'{width} × {height} px'
    elif detection.resolution or meta.get('resolution'):
        info['dimensions'] = detection.resolution or meta.get('resolution')

    if detection.file_type == 'video':
        info['duration'] = detection.duration or meta.get('duration') or 'Not determined'
        if meta.get('durationSeconds') is not None:
            info['duration'] = f'{info["duration"]} ({meta["durationSeconds"]} s)'
        info['fps'] = f'{meta["fps"]} fps' if meta.get('fps') else None
        info['codec'] = meta.get('codec')
    return info


def _risk_thresholds() -> tuple[float, float]:
    thresholds = current_app.config.get('RISK_THRESHOLDS', {})
    return thresholds.get('low', (0.0, 30.0))[1], thresholds.get('suspicious', (30.0, 70.0))[1]


def build_report_context(report: Report, detection: Detection) -> dict:
    """Everything the PDF prints, taken from the stored report, detection and evidence."""
    evidence = detection.evidence.order_by(Evidence.id).first()
    meta = _load_json(detection.metadata_json, dict)
    analysis = meta.get('aiAnalysis') if isinstance(meta.get('aiAnalysis'), dict) else {}
    is_demo = bool(detection.is_demo)
    is_video = detection.file_type == 'video'

    verdict = VERDICTS.get((detection.result or '').lower(), 'UNDETERMINED')
    fake = detection.deepfake_probability if detection.deepfake_probability is not None else detection.confidence
    complement = detection.real_probability
    if complement is None and fake is not None:
        complement = round(100 - fake, 1)

    # Who produced the result
    stored_model = detection.model_name or None
    if is_demo:
        analysis_kind = 'Simulated demo result — no model inference was run'
        provider = 'None (no inference provider was called)'
        model = f'None (stored label: "{stored_model}")' if stored_model else 'None'
        source_name = None
    else:
        analysis_kind = 'AI model inference (vision language model)'
        from_groq = bool(stored_model) and stored_model.endswith(GROQ_SUFFIX)
        provider = analysis.get('provider') or ('Groq Cloud' if from_groq else None)
        model = analysis.get('model') or (stored_model[:-len(GROQ_SUFFIX)] if from_groq else stored_model)
        source_name = ' via '.join(part for part in (model, provider) if part) or 'the analysing model'

    # Notes on how the stored verdict relates to the stored score
    low_max, medium_max = _risk_thresholds()
    notes = []
    if analysis.get('verdictPolicy'):
        notes.append(analysis['verdictPolicy'])
    elif fake is None:
        notes.append('No manipulation likelihood is stored for this detection.')
    elif (verdict == 'REAL' and fake >= low_max) or (verdict == 'FAKE' and fake < low_max):
        notes.append(
            f'The stored verdict ({verdict}) is not consistent with the stored manipulation likelihood '
            f'({fake:.1f}%). Treat this result as inconclusive.'
        )

    indicators = []
    for item in _load_json(detection.indicators_json, list):
        if not isinstance(item, dict) or not str(item.get('name') or '').strip():
            continue
        score = item.get('score')
        if isinstance(score, bool) or not isinstance(score, (int, float)):
            score = None
        elif score > 1:
            score = score / 100
        indicators.append({'name': item['name'], 'score': score,
                           'severity': item.get('severity'), 'evidence': item.get('evidence')})

    frames = [f for f in _load_json(detection.frames_json, list) if isinstance(f, dict)] if is_video else []
    custody = [
        {'action': e.get('action'), 'by': e.get('by'), 'time': _utc_from_iso(e.get('time') or e.get('timestamp'))}
        for e in _load_json(evidence.chain_of_custody_json if evidence else None, list) if isinstance(e, dict)
    ]

    if is_demo:
        indicator_source = ('Simulated by the application\'s demo mode. Not produced by any model and not '
                            'measured from the media.')
        observations_source = 'Demo mode; no model produced observations for this media.'
        no_indicators = 'No indicators are stored for this demo result.'
    else:
        indicator_source = (f'AI-generated observations reported by {source_name}. They describe what the model '
                            'stated it saw. FAKENIX did not independently measure or verify them.')
        observations_source = (f'Written assessment returned by {source_name}, reproduced as stored. It is the '
                               'model\'s opinion, not an independently verified forensic finding.')
        no_indicators = 'The model reported no specific manipulation indicators for this media.'

    limitations = [
        'The verdict is an automated assessment by a general-purpose vision language model. It can be wrong in '
        'either direction: manipulated media can be rated REAL and genuine media can be rated FAKE.',
        'The manipulation likelihood is the model\'s self-reported estimate. It has not been calibrated against '
        'a labelled dataset and must not be read as a measured accuracy or error rate.',
        ('Only the sampled frames listed in this report were sent to the model, downscaled and re-encoded as '
         'JPEG. The remaining frames and the audio track were not analysed.') if is_video else
        ('The model analysed a copy of the image that may have been downscaled and re-encoded as JPEG; very '
         'fine pixel-level traces can be lost in that step.'),
        'File metadata can be absent or deliberately altered. Missing EXIF data is common for media shared '
        'through social platforms and is not by itself evidence of manipulation.',
        'Hash verification covers the file as received by FAKENIX. Nothing in this report establishes where the '
        'media came from or what happened to it before upload.',
    ]
    if is_demo:
        # The model-related caveats do not apply: no model was involved.
        limitations = ['This is a demo result: no analysis of the media took place. The verdict, likelihood and '
                       'indicators are simulated placeholders.'] + limitations[-2:]

    return {
        'report_id': report.report_uid,
        'report_type': 'Forensic Analysis Report',
        'generated_at': _utc(report.created_at),
        'generated_by': report.generated_by or 'FAKENIX System',
        'evidence_id': evidence.evidence_uid if evidence else None,
        'detection_id': detection.detection_uid,
        'is_demo': is_demo,
        'verdict': verdict,
        'verdict_label': verdict,
        'risk_level': detection.risk_level,
        'fake_likelihood': fake,
        'authentic_complement': complement,
        'analysis_kind': analysis_kind,
        'model': model,
        'provider': provider,
        'analyzed_at': None if is_demo else (_utc_from_iso(analysis.get('analyzedAt')) or _utc(detection.created_at)),
        'notes': notes,
        'risk_bands': (f'below {low_max:.0f}% low, {low_max:.0f}–{medium_max:.0f}% medium, '
                       f'{medium_max:.0f}% and above high, 95% and above critical'),
        'file': _file_info(detection, evidence, meta),
        'integrity': check_evidence_integrity(evidence),
        'custody': custody,
        'indicators': indicators,
        'indicator_source': indicator_source,
        'no_indicators_text': no_indicators,
        'frames': frames,
        'observations': None if is_demo else (meta.get('aiExplanation') or None),
        'observations_source': observations_source,
        'no_observations_text': ('No written observations exist for a demo result.' if is_demo else
                                 'No written observations were stored for this detection.'),
        'limitations': limitations,
    }
