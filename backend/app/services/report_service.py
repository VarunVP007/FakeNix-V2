"""
FAKENIX 2.0 — Forensic Report Service

Creates one report record per detection, builds the report content from the
stored detection and evidence records, and renders it to PDF (layout lives in
app.services.report_pdf). Reports are stored in backend/storage/reports/.

Rules this module holds to:
  - A report is only ever created for a detection that exists. A missing
    detection or report is an error for the caller, never a reason to make one up.
  - Everything printed comes from the stored records or is measured from the
    stored evidence file. Missing values are shown as missing.
  - Downloading never creates a report; it serves the stored PDF, rebuilding the
    file under the same report ID only if it is absent or from an older layout.

DISCLAIMER: These reports are generated by FAKENIX AI software and are
intended for informational purposes only. They do not constitute official
government evidence or legal documentation.
"""
import json
import os
import re
from datetime import datetime, timezone
from flask import current_app
from sqlalchemy.exc import IntegrityError

from app.extensions import db
from app.models.report import Report
from app.models.detection import Detection
from app.models.evidence import Evidence
from app.services.hashing_service import calculate_sha256
from app.services.metadata_service import extract_basic_metadata
from app.utils.ids import next_sequential_id
from app.utils.logger import get_logger

logger = get_logger('report_service')

# Bump when the PDF layout or wording changes. A stored PDF from an older layout
# is rebuilt on its next download into a new file; the old file is left in place.
REPORT_LAYOUT_VERSION = 2

DETECTION_NOT_FOUND = 'Detection not found.'
REPORT_TYPE = 'Forensic Analysis'

VERDICTS = {'real': 'REAL', 'authentic': 'REAL', 'deepfake': 'FAKE', 'fake': 'FAKE', 'suspicious': 'SUSPICIOUS'}
GROQ_SUFFIX = ' (Groq)'


# ──────────────────────────────────────────────────────────────
# Report records
# ──────────────────────────────────────────────────────────────

def _visible_to(record_user_id, user_id) -> bool:
    """A record is visible to its owner; records without an owner are shared."""
    return record_user_id is None or record_user_id == user_id


def _find_detection(detection_ref, user_id) -> Detection | None:
    ref = str(detection_ref)
    detection = db.session.query(Detection).filter(Detection.detection_uid == ref).first()
    if not detection and ref.isdigit():
        detection = db.session.get(Detection, int(ref))
    if detection and not _visible_to(detection.user_id, user_id):
        return None
    return detection


def _report_for_detection(detection_id: int) -> Report | None:
    # Oldest first, so the answer is stable even if historical duplicates exist.
    return db.session.query(Report).filter(Report.detection_id == detection_id).order_by(Report.id).first()


def generate_report(detection_ref, user=None, user_id: int = None) -> tuple[Report | None, str]:
    """
    Return the report for a detection, creating it (and its PDF) on first request.

    Args:
        detection_ref: Detection UID string or ID
        user: User object of the requester (or None)
        user_id: requester's ID for ownership checks; defaults to user.id

    Returns:
        (report, error_message). error_message is DETECTION_NOT_FOUND when the
        detection does not exist or is not visible to the requester.
    """
    if user_id is None and user is not None:
        user_id = getattr(user, 'id', None)

    detection = _find_detection(detection_ref, user_id)
    if not detection:
        return None, DETECTION_NOT_FOUND
    if detection.status != 'complete' or not detection.result:
        return None, 'This detection has no completed analysis result to report on.'
    detection_id = detection.id

    report = _report_for_detection(detection_id)
    if not report:
        report = _create_report_record(detection_id, user)
        if not report:
            return None, 'Could not allocate a unique report ID. Please try again.'

    error = _ensure_pdf(report)
    if error:
        return None, error
    return report, ''


def _create_report_record(detection_id: int, user) -> Report | None:
    """
    Insert the report row, which reserves its ID, before any PDF is written.

    Two unique indexes make this safe under concurrent requests: report_uid (two
    requests proposing the same next ID) and detection_id (two requests for the
    same detection). The loser of either race rolls back and either adopts the
    winner's report or retries with the next ID.
    """
    for _ in range(5):
        report = Report(
            report_uid=_next_report_uid(),
            user_id=user.id if user is not None and getattr(user, 'id', None) else None,
            detection_id=detection_id,
            report_type=REPORT_TYPE,
            status='generating',
            generated_by=(getattr(user, 'full_name', None) or 'FAKENIX System'),
        )
        db.session.add(report)
        try:
            db.session.commit()
            logger.info(f'Report record created: {report.report_uid}')
            return report
        except IntegrityError:
            db.session.rollback()
            existing = _report_for_detection(detection_id)
            if existing:
                return existing
    return None


def _next_report_uid() -> str:
    """
    Propose the next FX-RPT-<year>-<n> ID.

    Numbers are never reissued: besides the IDs in the table, PDFs already in the
    report folder count as used, so an ID whose row was deleted cannot be handed
    to a different detection (and its old PDF cannot be overwritten).
    """
    year = datetime.now(timezone.utc).year
    floor = 0
    pattern = re.compile(rf'^FX_RPT_{year}_(\d+)(?:_v\d+)?\.pdf$')
    try:
        for name in os.listdir(_report_folder()):
            match = pattern.match(name)
            if match:
                floor = max(floor, int(match.group(1)))
    except OSError:
        pass
    return next_sequential_id(Report.report_uid, f'FX-RPT-{year}-', 3, floor=floor)


def get_all_reports(user_id: int = None) -> list:
    """Reports owned by the user, plus reports that have no owner."""
    reports = (
        db.session.query(Report)
        .filter(db.or_(Report.user_id == user_id, Report.user_id.is_(None)))
        .order_by(Report.created_at.desc())
        .all()
    )
    return [r.to_dict() for r in reports]


def get_report_by_uid(report_uid: str, user_id: int = None) -> Report | None:
    """Get a single report by UID, if it is visible to the user."""
    uid = str(report_uid)
    report = db.session.query(Report).filter(Report.report_uid == uid).first()
    if not report and uid.startswith('rpt_') and uid[4:].isdigit():
        report = db.session.get(Report, int(uid[4:]))
    if report and not _visible_to(report.user_id, user_id):
        return None
    return report


# ──────────────────────────────────────────────────────────────
# PDF files
# ──────────────────────────────────────────────────────────────

def _report_folder() -> str:
    return current_app.config.get('REPORT_FOLDER', 'storage/reports')


def _pdf_filename(report_uid: str) -> str:
    return f'{report_uid.replace("-", "_")}_v{REPORT_LAYOUT_VERSION}.pdf'


def _is_current_layout(filename: str | None) -> bool:
    return bool(filename) and filename.endswith(f'_v{REPORT_LAYOUT_VERSION}.pdf')


def get_report_path(report: Report) -> str | None:
    """Return the absolute path to the report PDF, or None if it is not on disk."""
    if not report or not report.report_path:
        return None
    full_path = os.path.join(_report_folder(), os.path.basename(report.report_path))
    return full_path if os.path.exists(full_path) else None


def get_report_pdf(report: Report) -> tuple[str | None, str]:
    """
    Path of the PDF to serve for an existing report: (path, error_message).
    Never creates report, detection or evidence records.
    """
    error = _ensure_pdf(report)
    if error:
        return None, error
    return get_report_path(report), ''


def _ensure_pdf(report: Report) -> str:
    """
    Make sure the report has a current-layout PDF on disk, building it under the
    report's existing ID if needed. Returns an error message, or '' on success.
    """
    current = get_report_path(report)
    if current and _is_current_layout(report.report_path):
        return ''

    detection = report.detection
    if detection is None:
        if current:
            # The source records are gone; the stored PDF is all there is.
            return ''
        return 'The detection this report was generated from no longer exists.'

    filename = _pdf_filename(report.report_uid)
    os.makedirs(_report_folder(), exist_ok=True)
    try:
        from app.services.report_pdf import render_report_pdf
        render_report_pdf(os.path.join(_report_folder(), filename), build_report_context(report, detection))
    except Exception as e:
        logger.exception(f'PDF generation error for {report.report_uid}: {e}')
        report.status = 'error'
        db.session.commit()
        return 'Report PDF generation failed.'

    report.report_path = filename
    report.status = 'ready'
    db.session.commit()
    logger.info(f'Report PDF written: {filename}')
    return ''


