import { useState, useEffect } from 'react'
import { useParams, useLocation, Link, useNavigate } from 'react-router-dom'
import {
  Download, AlertTriangle, RefreshCw, ArrowLeft,
  FileVideo, FileImage, Clock, Cpu, Shield, Copy
} from 'lucide-react'
import { detectionService } from '../services/detectionService'
import { ResultBadge, RiskBadge } from '../components/common/Badge'
import DetectionResult from '../components/detection/DetectionResult'
import RiskScore from '../components/detection/RiskScore'
import MetadataPanel from '../components/forensic/MetadataPanel'
import HashDisplay from '../components/forensic/HashDisplay'
import { useToast } from '../App'
import { formatDateTime } from '../utils/formatters'
import { getRiskColor } from '../utils/riskCalculator'

const SEVERITY_COLORS = { high: 'var(--red)', medium: 'var(--orange)', low: 'var(--green)' }

export default function Result() {
  const { id } = useParams()
  const location = useLocation()
  const navigate = useNavigate()
  const { addToast } = useToast()
  const [det, setDet] = useState(location.state?.result || null)
  const [loading, setLoading] = useState(!det)
  const [activeTab, setActiveTab] = useState('analysis')
  const [downloading, setDownloading] = useState(false)
  const [reportId, setReportId] = useState(det?.reportId || null)

  useEffect(() => {
    if (!det) {
      detectionService.getDetectionResult(id).then((d) => {
        setDet(d)
        setLoading(false)
      })
    }
  }, [id, det])

  if (loading) return (
    <div style={{ display: 'flex', justifyContent: 'center', alignItems: 'center', minHeight: '60vh' }}>
      <div className="loader-spinner lg" />
    </div>
  )
  if (!det) return <div className="empty-state"><h2>Detection not found</h2></div>

  const verdictClass = det.result === 'deepfake' ? 'deepfake' : det.result === 'real' ? 'real' : 'suspicious'
  const riskColor = getRiskColor(det.risk)

  const handleDownloadReport = async () => {
    setDownloading(true)
    try {
      let activeReportId = reportId
      if (!activeReportId) {
        addToast('Generating forensic PDF report...', 'info', 'Generating Report')
        const targetId = det?.id || id || 'det_001'
        const rptRes = await detectionService.generateReport(targetId)
        activeReportId = rptRes?.reportId || rptRes?.data?.reportId || 'FX-RPT-2026-001'
        setReportId(activeReportId)
      }

      addToast(`Initiating download for ${activeReportId}...`, 'info', 'Downloading')
      await detectionService.downloadReport(activeReportId)
      addToast(`Report ${activeReportId} downloaded successfully.`, 'success', 'Download Complete')
    } catch (err) {
      console.error('Failed to download report:', err)
      addToast('Unable to download report. Please try again.', 'error', 'Download Failed')
    } finally {
      setDownloading(false)
    }
  }

  const tabs = ['analysis', ...(det.fileType === 'video' ? ['frames'] : []), 'metadata', 'evidence']

  return (
    <div className="animate-slideUp">
      {/* Back */}
      <button className="btn btn-ghost btn-sm" onClick={() => navigate(-1)} style={{ marginBottom: 16 }}>
        <ArrowLeft size={14} /> Back
      </button>

      {/* Demo banner */}
      <div style={{
        display: 'flex', alignItems: 'center', gap: 10,
        background: 'linear-gradient(90deg, #f5f3ff, #eff6ff)',
        border: '1px solid #ddd6fe',
        borderRadius: 'var(--radius)', padding: '8px 16px', marginBottom: 20, fontSize: 13
      }}>
        <span className="demo-badge">DEMO ANALYSIS</span>
        <span style={{ color: 'var(--text-secondary)' }}>
          This result was generated by a simulation. No real AI model was invoked.
        </span>
      </div>

      {/* Verdict Card */}
      <div className={`result-verdict ${verdictClass}`} style={{ marginBottom: 24 }}>
        <div style={{ fontSize: 40, marginBottom: 8 }}>
          {det.result === 'deepfake' ? '⚠️' : det.result === 'real' ? '✅' : '🔍'}
        </div>
        <div className={`verdict-label ${verdictClass}`}>
          {det.result === 'deepfake' ? 'DEEPFAKE DETECTED'
            : det.result === 'real' ? 'AUTHENTIC MEDIA'
            : 'SUSPICIOUS MEDIA'}
        </div>
        <RiskScore score={det.deepfakeProbability} result={det.result} risk={det.risk} />
        <div style={{ marginTop: 8 }}>
          <RiskBadge risk={det.risk} />
        </div>
        <div style={{ marginTop: 12, fontSize: 14, color: 'var(--text-secondary)' }}>
          {det.fileName} &nbsp;·&nbsp; Evidence ID: <strong className="evidence-id">{det.evidenceId}</strong>
        </div>
      </div>

      {/* Confidence bars */}
      <div className="grid-2" style={{ marginBottom: 24 }}>
        <div className="card">
          <div className="card-title" style={{ marginBottom: 14 }}>Detection Probabilities</div>
          <DetectionResult
            result={det.result}
            confidence={det.confidence}
            deepfakeProbability={det.deepfakeProbability}
            realProbability={det.realProbability}
          />
        </div>

        {/* File Info */}
        <div className="card">
          <div className="card-title" style={{ marginBottom: 14 }}>File Information</div>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
            {[
              ['File Name', det.fileName],
              ['File Type', det.fileType?.toUpperCase()],
              ['File Size', det.fileSize],
              ['Resolution', det.resolution || 'N/A'],
              ...(det.duration ? [['Duration', det.duration]] : []),
              ['Upload Time', formatDateTime(det.timestamp)],
              ['AI Model', det.model]
            ].map(([label, value]) => (
              <div key={label} style={{ display: 'flex', justifyContent: 'space-between', fontSize: 13, borderBottom: '1px solid #f1f5f9', paddingBottom: 8 }}>
                <span style={{ color: 'var(--text-muted)', fontWeight: 500 }}>{label}</span>
                <span style={{ fontWeight: 600, color: 'var(--text-primary)', textAlign: 'right', maxWidth: '60%' }}>{value}</span>
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* Tabs */}
      <div className="card" style={{ marginBottom: 24 }}>
        <div className="tabs">
          {tabs.map((t) => (
            <button
              key={t}
              className={`tab-btn ${activeTab === t ? 'active' : ''}`}
              onClick={() => setActiveTab(t)}
            >
              {t === 'analysis' ? 'AI Analysis'
                : t === 'frames' ? 'Frame Analysis'
                : t === 'metadata' ? 'Metadata'
                : 'Evidence'}
            </button>
          ))}
        </div>

        {/* Analysis Tab */}
        {activeTab === 'analysis' && (
          <div>
            <div style={{ marginBottom: 20 }}>
              <div style={{ fontWeight: 700, fontSize: 15, marginBottom: 4 }}>Why was this detected?</div>
              <div style={{ fontSize: 13, color: 'var(--text-secondary)', marginBottom: 14 }}>
                The AI model identified the following indicators during analysis:
              </div>
              <div className="indicators-list">
                {(det.indicators || []).map((ind) => (
                  <div key={ind.name} className="indicator-item">
                    <div
                      className="indicator-dot"
                      style={{ background: SEVERITY_COLORS[ind.severity] }}
                    />
                    <span className="indicator-name">{ind.name}</span>
                    <div className="indicator-bar">
                      <div
                        className="indicator-bar-fill"
                        style={{
                          width: `${ind.score * 100}%`,
                          background: SEVERITY_COLORS[ind.severity]
                        }}
                      />
                    </div>
                    <span className="indicator-score">{(ind.score * 100).toFixed(0)}%</span>
                    <RiskBadge risk={ind.severity} />
                  </div>
                ))}
                {(!det.indicators || det.indicators.length === 0) && (
                  <p style={{ color: 'var(--text-muted)', fontStyle: 'italic', fontSize: 13 }}>
                    No specific indicators detected for this media.
                  </p>
                )}
              </div>
            </div>

            {/* Visual explanation placeholder */}
            <div style={{ marginTop: 20 }}>
              <div style={{ fontWeight: 700, fontSize: 15, marginBottom: 12 }}>Visual Explanation</div>
              <div style={{ display: 'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap: 12 }}>
                {['Original Frame', 'Analyzed Frame', 'AI Heatmap (Grad-CAM)'].map((label) => (
                  <div key={label} style={{
                    background: 'linear-gradient(135deg, #1e293b, #334155)',
                    borderRadius: 10, aspectRatio: '16/9',
                    display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center',
                    gap: 8
                  }}>
                    <div style={{
                      width: '60%', height: '60%', borderRadius: 4,
                      background: label === 'AI Heatmap (Grad-CAM)'
                        ? 'linear-gradient(135deg, rgba(239,68,68,0.6), rgba(249,115,22,0.3))'
                        : 'rgba(255,255,255,0.05)',
                      border: '1px solid rgba(255,255,255,0.1)'
                    }} />
                    <span style={{ fontSize: 10, color: '#64748b', fontWeight: 600 }}>{label}</span>
                  </div>
                ))}
              </div>
            </div>
          </div>
        )}

        {/* Frames Tab */}
        {activeTab === 'frames' && det.frames?.length > 0 && (
          <div>
            <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: 14 }}>
              <div style={{ fontWeight: 700, fontSize: 15 }}>Frame-Level Analysis</div>
              <Link to={`/result/${id}/frames`} className="btn btn-secondary btn-sm">
                Full Frame View
              </Link>
            </div>
            <div className="frame-grid">
              {det.frames.map((frame) => (
                <div key={frame.frameNum} className="frame-card">
                  <div className="frame-preview">
                    <span style={{ fontSize: 9 }}>Frame Preview</span>
                  </div>
                  <div className="frame-number">Frame {String(frame.frameNum).padStart(3, '0')}</div>
                  <div className="frame-probability" style={{ color: getRiskColor(frame.risk) }}>
                    {frame.probability}%
                  </div>
                  <div className="frame-timestamp">{frame.timestamp}</div>
                </div>
              ))}
            </div>
          </div>
        )}
        {activeTab === 'frames' && (!det.frames || det.frames.length === 0) && (
          <p style={{ color: 'var(--text-muted)', fontStyle: 'italic', fontSize: 13 }}>
            Frame analysis not available for this media type.
          </p>
        )}

        {/* Metadata Tab */}
        {activeTab === 'metadata' && (
          <div>
            <div style={{ fontWeight: 700, fontSize: 15, marginBottom: 14 }}>File Metadata</div>
            <MetadataPanel metadata={det.metadata} />
          </div>
        )}

        {/* Evidence Tab */}
        {activeTab === 'evidence' && (
          <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
            <div style={{ fontWeight: 700, fontSize: 15, marginBottom: 4 }}>Forensic Evidence Information</div>
            <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
              <div className="card" style={{ background: 'var(--bg-main)' }}>
                <div style={{ fontSize: 12, fontWeight: 700, color: 'var(--text-muted)', textTransform: 'uppercase', letterSpacing: 0.5, marginBottom: 8 }}>
                  Evidence ID
                </div>
                <div className="evidence-id" style={{ fontSize: 18, fontWeight: 900 }}>{det.evidenceId}</div>
              </div>
              <HashDisplay hash={det.sha256} label="SHA-256 Hash" />
              <div style={{ display: 'flex', gap: 12, flexWrap: 'wrap' }}>
                {[
                  ['Detection Model', det.model],
                  ['Timestamp', formatDateTime(det.timestamp)],
                  ['Result', det.result?.toUpperCase()],
                  ['Risk Level', det.risk?.toUpperCase()]
                ].map(([label, value]) => (
                  <div key={label} style={{
                    flex: '1 1 160px',
                    background: 'var(--bg-main)',
                    border: '1px solid var(--border)',
                    borderRadius: 10,
                    padding: '12px 16px'
                  }}>
                    <div style={{ fontSize: 11, fontWeight: 700, color: 'var(--text-muted)', textTransform: 'uppercase', letterSpacing: 0.5, marginBottom: 4 }}>
                      {label}
                    </div>
                    <div style={{ fontWeight: 700, fontSize: 13, color: 'var(--text-primary)' }}>{value}</div>
                  </div>
                ))}
              </div>
            </div>
          </div>
        )}
      </div>

      {/* Actions */}
      <div style={{ display: 'flex', gap: 12, flexWrap: 'wrap' }}>
        <button className="btn btn-primary" onClick={handleDownloadReport} disabled={downloading}>
          {downloading ? <div className="loader-spinner sm" /> : <Download size={15} />}
          <span>{downloading ? 'Downloading...' : 'Download Forensic Report'}</span>
        </button>
        <Link to="/cybercrime/report" className="btn btn-danger">
          <AlertTriangle size={15} /> Report Cybercrime
        </Link>
        <Link to="/detect" className="btn btn-secondary">
          <RefreshCw size={15} /> Analyze Another File
        </Link>
        {det.fileType === 'video' && det.frames?.length > 0 && (
          <Link to={`/result/${id}/frames`} className="btn btn-outline">
            View All Frames
          </Link>
        )}
      </div>
    </div>
  )
}
